import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const imports = new Map();
let records = 0;
const knownCountry = value => typeof value === 'string' && value.trim() &&
  !/not stated|requires|unknown|not displayed|not provided|seller input/i.test(value)
  ? value.trim() : null;

async function collect(directory) {
  for (const item of (await readdir(directory, {withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))) {
    const path = join(directory,item.name);
    if (item.isDirectory()) {
      if (!['images','.image-review'].includes(item.name)) await collect(path);
    } else if (item.name === 'product-data.json') {
      const raw = JSON.parse(await readFile(path,'utf8'));
      const asin = raw.source?.asin?.toUpperCase();
      if (!asin) continue;
      const names = [...new Set([
        raw.listing?.storefrontTitle, raw.listing?.title, raw.listing?.titleEn, raw.listing?.nameEn,
        raw.rewrittenMarketingCopy?.storefrontTitle, raw.rewrittenMarketingCopy?.title,
        raw.verifiedSourceFacts?.sourceTitle, raw.verifiedFacts?.sourceTitle,
        raw.source?.sourceTitle, raw.source?.title,
      ].filter(value=>typeof value==='string'&&value.trim()).map(value=>value.trim()))];
      if (!names.length) continue;
      records++;
      const country = knownCountry(raw.listing?.specifications?.countryOfOrigin ??
        raw.verifiedFacts?.countryOfOrigin ?? raw.verifiedSourceFacts?.countryOfOrigin);
      const entry = imports.get(asin) ?? {asin,name:names[0],aliases:new Set(),countries:new Set(),references:new Set()};
      names.forEach(name=>entry.aliases.add(name));
      if (country) entry.countries.add(country);
      entry.references.add(relative(project,path).replaceAll('\\','/'));
      imports.set(asin,entry);
    }
  }
}
await collect(join(project,'products'));
const entries = [...imports.values()].sort((a,b)=>a.asin.localeCompare(b.asin)).map(entry=>({
  asin:entry.asin,name:entry.name,aliases:[...entry.aliases].filter(name=>name!==entry.name),
  country:entry.countries.size===1?[...entry.countries][0]:null,
  references:[...entry.references],
}));
await writeFile(join(project,'lib/products/import-provenance.ts'),
  '// Generated by scripts/generate-product-import-provenance.mjs from every saved import JSON shape.\n'+
  '// Source declarations remain unverified. Originals and internal references stay private; no price or stock data is included.\n'+
  'export const recordedImports = '+JSON.stringify(entries,null,2)+' as const;\n');
console.log('Indexed '+records+' original records, '+entries.length+' source products, with all recorded title aliases.');
